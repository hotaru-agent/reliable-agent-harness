"""Observability layer for the reliable agent harness (Phase 6).

Provides the OpenTelemetry tracing foundation: instrumentation scope,
span names, attribute namespace, safe-telemetry helpers, exception
privacy policy, and safe span lifecycle management.

This package does NOT configure a global ``TracerProvider`` or install
any exporter. Core runtime modules accept an injected ``Tracer`` (or
fall back to the no-op API default). Application bootstrap is
responsible for SDK configuration.

Telemetry failure must never become business failure.
"""

